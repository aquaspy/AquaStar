// Regenerate the translator templates from the en-US catalogs:
//   res/po/en-US.js                                   -> res/po/template.js
//   plugins/<id>/locales/en-US.js (each bundled one)  -> plugins/<id>/locales/template.js
//
// A template has exactly the keys of its en-US catalog with every text emptied, so
// translators always start from the real structure. test/unit/locale-templates.test.js fails
// when a template drifts from its catalog; run `node scripts/make-locale-templates.js`.

const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');

function key(name) {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : JSON.stringify(name);
}

// A function in a catalog (e.g. helpDetail) is kept so the template stays runnable, with
// its text literals emptied.
function emptyFunction(fn, indent) {
  const source = String(fn)
    .replace(/"(?:[^"\\]|\\.)*"/g, '""')
    .replace(/'(?:[^'\\]|\\.)*'/g, "''");
  return source.split('\n').map(function (line, i) { return i === 0 ? line : indent + line.replace(/^ {0,4}/, ''); }).join('\n');
}

function emit(obj, indent) {
  const inner = indent + '    ';
  return Object.keys(obj).map(function (name) {
    const value = obj[name];
    if (typeof value === 'function') {
      const source = emptyFunction(value, inner);
      // `name(k) {}` is already a method; `function (k) {}` / arrows need the key in front.
      return /^(async\s+)?(function\b|\(|[A-Za-z_$][\w$]*\s*=>)/.test(source) ? inner + key(name) + ': ' + source : inner + source;
    }
    if (Array.isArray(value)) return inner + key(name) + ': [' + value.map(function () { return '""'; }).join(', ') + ']';
    if (value && typeof value === 'object') return inner + key(name) + ': {\n' + emit(value, inner) + '\n' + inner + '}';
    return inner + key(name) + ': ""';
  }).join(',\n');
}

function renderTemplate(catalog, sourceLabel) {
  const names = Object.keys(catalog);
  const hasFunction = JSON.stringify(catalog, function (k, v) { return typeof v === 'function' ? '__fn__' : v; }).indexOf('__fn__') !== -1;
  const parts = [
    '// Translator template: the keys of ' + sourceLabel + ' with every text emptied.',
    '// Generated by scripts/make-locale-templates.js - do not edit by hand.',
    ''
  ];
  if (hasFunction) {
    parts.push('function expand (keyb) {if(Array.isArray(keyb)) return keyb.join(\', \'); else return keyb;};', '');
  }
  names.forEach(function (name) {
    parts.push('exports.' + name + ' = {\n' + emit(catalog[name], '') + '\n};', '');
  });
  return parts.join('\n');
}

// res/locale.js merges plugin strings into the cached catalog module at runtime, so a process
// that has booted the app sees more keys than the file declares. Always read the file afresh.
function loadCatalog(file) {
  const resolved = require.resolve(file);
  delete require.cache[resolved];
  const catalog = require(resolved);
  delete require.cache[resolved];
  return catalog;
}

function targets() {
  const list = [{ catalog: path.join(root, 'res', 'po', 'en-US.js'), out: path.join(root, 'res', 'po', 'template.js'), label: 'res/po/en-US.js' }];
  const pluginsDir = path.join(root, 'plugins');
  fs.readdirSync(pluginsDir).sort().forEach(function (dir) {
    const catalog = path.join(pluginsDir, dir, 'locales', 'en-US.js');
    if (fs.existsSync(catalog)) {
      list.push({ catalog: catalog, out: path.join(pluginsDir, dir, 'locales', 'template.js'), label: 'plugins/' + dir + '/locales/en-US.js' });
    }
  });
  return list;
}

if (require.main === module) {
  targets().forEach(function (t) {
    fs.writeFileSync(t.out, renderTemplate(loadCatalog(t.catalog), t.label));
    console.log('wrote ' + path.relative(root, t.out));
  });
}

module.exports = { renderTemplate: renderTemplate, targets: targets, loadCatalog: loadCatalog };
